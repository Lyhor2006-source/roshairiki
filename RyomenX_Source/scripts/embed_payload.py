#!/usr/bin/env python3
import os
import sys

def main():
    script_dir = os.path.dirname(os.path.abspath(__file__))
    project_dir = os.path.dirname(script_dir)
    src_py = os.path.join(script_dir, "neox_battle_payload.py")
    out_hpp = os.path.join(project_dir, "include", "EmbeddedPayload.hpp")

    if not os.path.isfile(src_py):
        print(f"Error: {src_py} not found", file=sys.stderr)
        sys.exit(1)

    with open(src_py, "rb") as f:
        data = f.read().replace(b"\r\n", b"\n").replace(b"\r", b"\n")

    print(f"Embedding {len(data)} bytes from {src_py} into {out_hpp}...")

    # Write as const char array with null terminator
    lines = []
    lines.append("// Auto-generated by scripts/embed_payload.py. Do not edit manually.")
    lines.append("#pragma once")
    lines.append("")
    lines.append("namespace RyomenX {")
    lines.append("")
    lines.append(f"// Embedded NeoX battle payload ({len(data)} bytes)")
    lines.append("static const char EMBEDDED_PAYLOAD[] = {")

    chunk_size = 16
    for i in range(0, len(data), chunk_size):
        chunk = data[i:i + chunk_size]
        hex_vals = ", ".join(f"0x{b:02x}" for b in chunk)
        lines.append(f"    {hex_vals},")

    lines.append("    0x00")
    lines.append("};")
    lines.append("")
    lines.append("} // namespace RyomenX")
    lines.append("")

    with open(out_hpp, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))

    print(f"Successfully generated {out_hpp} ({os.path.getsize(out_hpp)} bytes)")

if __name__ == "__main__":
    main()
